private val emojiCategories = listOf("Recent", "Smileys", "People", "Animals", "Food", "Activities", "Travel", "Objects", "Symbols")

@Composable
internal fun ChatEmojiPicker(onSelect: (String) -> Unit) {
    val context = LocalContext.current
    val prefs = remember(context) { context.getSharedPreferences("spotifygood_recent_tapbacks", 0) }
    var recentlyUsed by remember { mutableStateOf(prefs.getString("symbols", "")
        .orEmpty().split('|').filter { it.isNotBlank() }.take(24)) }
    var search by remember { mutableStateOf("") }
    var selectedCategory by remember { mutableStateOf("Smileys") }
    val all = remember(recentlyUsed) { recentlyUsed.mapNotNull { symbol ->
        chatEmojis.firstOrNull { it.symbol == symbol }
    } }
    val shown = when {
        search.isNotBlank() -> chatEmojis.filter { choice ->
            search.trim().split(Regex("\\s+")).all { term ->
                choice.search.contains(term, ignoreCase = true) || choice.symbol == term
            }
        }
        selectedCategory == "Recent" -> all
        else -> chatEmojis.filter { it.category == selectedCategory }
    }.distinctBy { it.symbol }
    Column(Modifier.fillMaxWidth().padding(horizontal = 12.dp, vertical = 8.dp)) {
        Text("React with an emoji", modifier = Modifier.padding(horizontal = 7.dp, vertical = 6.dp),
            style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.Bold)
        OutlinedTextField(value = search, onValueChange = { search = it },
            modifier = Modifier.fillMaxWidth(), singleLine = true,
            placeholder = { Text("Search emoji (e.g. happy, heart, fire)") })
        Spacer(Modifier.height(8.dp))
        Row(Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()),
            horizontalArrangement = Arrangement.spacedBy(6.dp)) {
            emojiCategories.forEach { category ->
                FilterChip(selected = selectedCategory == category && search.isBlank(),
                    onClick = { selectedCategory = category; search = "" },
                    label = { Text(category) })
            }
        }
        if (shown.isEmpty()) {
            Text(if (selectedCategory == "Recent" && search.isBlank()) "You haven't used any emoji reactions yet"
                else "No matching emoji", modifier = Modifier.padding(12.dp),
                color = MaterialTheme.colorScheme.onSurfaceVariant)
        } else {
            LazyVerticalGrid(columns = GridCells.Fixed(8), modifier = Modifier.fillMaxWidth().height(350.dp),
                verticalArrangement = Arrangement.spacedBy(4.dp)) {
                items(shown, key = { it.symbol }) { item ->
                    Box(Modifier.size(43.dp).clickable {
                        recentlyUsed = (listOf(item.symbol) + recentlyUsed.filterNot { it == item.symbol }).take(24)
                        prefs.edit().putString("symbols", recentlyUsed.joinToString("|")).apply()
                        onSelect(item.symbol)
                    }, contentAlignment = Alignment.Center) {
                        Text(item.symbol, fontSize = 26.sp)
                    }
                }
            }
        }
        Spacer(Modifier.height(18.dp))
    }
}
